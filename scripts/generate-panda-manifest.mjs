// Rust declarations -> public JSON Schema -> frontend author-manifest types.
// This command never reads or initializes a workspace or application directory.
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { root, rustEnvironment } from './process.mjs';

const arguments_ = process.argv.slice(2);
if (arguments_.some(argument => argument !== '--check') || arguments_.length > 1) throw new Error('Usage: node scripts/generate-panda-manifest.mjs [--check]');
const check = arguments_.includes('--check');
const result = spawnSync('cargo', ['run', '--locked', '--quiet', '-p', 'platform-core', '--example', 'panda_manifest_schema'], {
  cwd: root, env: rustEnvironment(), encoding: 'utf8', maxBuffer: 8 * 1024 * 1024,
  windowsHide: true,
});
if (result.error) throw result.error;
if (result.status !== 0) throw new Error(result.stderr || 'Panda manifest schema exporter failed.');
const schema = JSON.parse(result.stdout);
const generatedTypes = await compile(schema, 'PandaManifest', {
  bannerComment: '// Generated by scripts/generate-panda-manifest.mjs from platform-core Rust declarations. Do not edit.',
  additionalProperties: false,
  unreachableDefinitions: true,
  ignoreMinAndMaxItems: true,
  style: { singleQuote: true, semi: true, tabWidth: 2, printWidth: 120 },
});
const outputs = [
  ['schemas/panda.schema.json', `${JSON.stringify(schema, null, 2)}\n`],
  ['apps/desktop/src/generated/panda-manifest.ts', generatedTypes],
];
for (const [relative, contents] of outputs) {
  const filename = path.join(root, relative);
  if (check) {
    let current;
    try { current = await readFile(filename, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current !== contents) throw new Error(`${relative} is stale; run node scripts/generate-panda-manifest.mjs.`);
  } else {
    await mkdir(path.dirname(filename), { recursive: true });
    await writeFile(filename, contents);
  }
}
console.log(check ? 'Panda manifest schema and frontend types are current.' : 'Generated Panda manifest schema and frontend types.');
