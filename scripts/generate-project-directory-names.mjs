// Generates committed, offline naming data from the pinned npm implementation.
// No application, project directory, user data or npm lifecycle script is run.
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { transliterate, slugify } from 'transliteration';

const require = createRequire(import.meta.url);
const version = '2.6.2';
const packagePath = require.resolve('transliteration/package.json');
const metadata = JSON.parse(await readFile(packagePath, 'utf8'));
if (metadata.version !== version) throw new Error(`Expected transliteration ${version}, found ${metadata.version}`);
const check = process.argv.length === 3 && process.argv[2] === '--check';
if (process.argv.length > 2 && !check) throw new Error('Usage: node scripts/generate-project-directory-names.mjs [--check]');
const output = new URL('../crates/platform-core/src/project_directory_name_data/', import.meta.url);
const fragment = value => value.replace(/[^a-zA-Z0-9]+/g, '-').toLowerCase();
const anchor = transliterate('中', { fixChineseSpacing: false });
const rows = [];
for (const character of Object.keys(transliterate.setData()).sort((a, b) => a.codePointAt(0) - b.codePointAt(0))) {
  const code = character.codePointAt(0);
  if ([...character].length !== 1 || (code >= 0xd800 && code <= 0xdfff)) throw new Error('Unexpected non-scalar character mapping');
  const raw = transliterate(character, { fixChineseSpacing: false });
  if (!/^[\x00-\x7f]*$/.test(raw)) throw new Error(`Non-ASCII transliteration for ${code}`);
  const before = transliterate(`中${character}`);
  const after = transliterate(`${character}A`);
  const beforeBoundary = before === `${anchor} ${raw}`;
  const chinese = after === `${raw} A`;
  if (before !== `${anchor}${raw}` && !beforeBoundary) throw new Error(`Unexpected preceding boundary at ${code}`);
  if (after !== `${raw}A` && !chinese) throw new Error(`Unexpected following boundary at ${code}`);
  rows.push(`${code.toString(16)}\t${Number(chinese) | (Number(beforeBoundary) << 1)}\t${fragment(raw)}\n`);
}
const body = rows.join('');
const mapping = `# Generated by scripts/generate-project-directory-names.mjs; do not edit.\n# npm transliteration ${version}; MIT; see LICENSE.transliteration.txt.\n# scalar(hex) flags(chinese=1,boundary-before=2) ascii-fragment\n# body-sha256 ${createHash('sha256').update(body).digest('hex')}\n${body}`;
const reserved = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/;
const examples = [
  'Hello World', '你好，世界', '我的 App 2026', 'App应用', '音乐🎵笔记',
  'Crème brûlée & Straße', 'São Paulo', 'Привет мир', 'Γεια σου κόσμε',
  '東京のアプリ', '안녕하세요', 'नमस्ते दुनिया', 'مرحبا بالعالم', 'A\u0301B',
  'a½b', '中½A', '中文🧑‍💻ABC', '😀🚀', '...', '../../CON\\', 'CON', 'lPt9',
  '  a___b...c -- d  ', 'é'.repeat(80), `${'word-'.repeat(20)}end`,
];
// Fixed Cartesian coverage exercises spacing across script, punctuation,
// empty/unknown, combining and multi-scalar emoji boundaries. It is not a
// claim of equivalence for every Unicode string or configurable library mode.
const tokens = ['A', 'b', '中', '文', '日', 'あ', '한', 'é', '\u0301', '😀', '🧑‍💻', '\u{10ffff}', ' ', '-', '½', '\0'];
const combinations = tokens.flatMap(first => tokens.flatMap(second => tokens.map(third => first + second + third)));
const names = [...new Set([...examples, ...combinations])];
const fixtures = JSON.stringify({ package: 'transliteration', version, options: { allowedChars: 'a-zA-Z0-9', separator: '-', lowercase: true }, cases: names.map(name => {
  let slug = slugify(name, { allowedChars: 'a-zA-Z0-9', separator: '-', lowercase: true }).slice(0, 48).replace(/-+$/, '') || 'project';
  if (reserved.test(slug)) slug = `project-${slug}`;
  return { name, slug };
}) }, null, 2) + '\n';
const license = await readFile(new URL('./LICENSE.txt', pathToFileURL(packagePath)));
const files = [['mapping.tsv', mapping], ['golden.json', fixtures], ['LICENSE.transliteration.txt', license]];
if (!check) await mkdir(output, { recursive: true });
for (const [name, value] of files) {
  const target = new URL(name, output);
  const bytes = Buffer.isBuffer(value) ? value : Buffer.from(value);
  if (check) {
    if (!(await readFile(target)).equals(bytes)) throw new Error(`${fileURLToPath(target)} differs from pinned npm output; regenerate and review`);
  } else await writeFile(target, bytes);
}
console.log(`${check ? 'Verified' : 'Generated'} ${rows.length} pinned transliteration mappings and ${names.length} public-API golden cases.`);
